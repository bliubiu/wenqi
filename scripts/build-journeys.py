def build():
    journeys = []
    for key, data in RAW.items():
        stages = []
        for i, (era, place, modern, lng, lat, kind, event, *rest) in enumerate(data["stages"]):
            poem = rest[0] if rest else None
            stages.append({
                "seq": i,
                "era": era,
                "place": place,
                "modern": modern,
                "lng": lng,
                "lat": lat,
                "kind": kind,
                "event": event,
                "poem": poem,
            })
        journeys.append({
            "key": key,
            "name": data["name"],
            "dynasty": data["dynasty"],
            "summary": data["summary"],
            "stages": stages,
        })

    journeys.sort(key=lambda j: j["name"])
    doc = {
        "version": "2026.11.04.0",
        "source": (
            "王兆鹏《唐宋文学编年地图》(搜韵/cnkgraph.com/Map/PoetLife)、"
            "文汇网《数字人文揭谜：唐宋诗人行迹》、"
            "文旅山东《苏东坡的'流浪地图'》等公开资料整理；"
            "坐标为古今地名对应近似值，非测绘级精度。"
        ),
        "note": (
            "v1 为代表性诗人精选行迹种子数据。cnkgraph 人物接口仅含生卒年/籍贯/传记文本，"
            "不含结构化编年系地；若后续取得其编年系地后台接口或 CBDB 数据，可按相同 schema 回填并扩展覆盖。"
        ),
        "extensible": True,
        "generatedAt": "",
        "journeys": journeys,
    }
    return doc


if __name__ == "__main__":
    out_path = os.path.join(os.path.dirname(__file__), "..", "public", "data", "processed", "journeys.json")
    out_path = os.path.abspath(out_path)
    doc = build()
    doc["generatedAt"] = __import__("datetime").datetime.now(__import__("datetime").timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
    print(f"写入 {out_path}：共 {len(doc['journeys'])} 位诗人、"
          f"{sum(len(j['stages']) for j in doc['journeys'])} 个行迹阶段")
